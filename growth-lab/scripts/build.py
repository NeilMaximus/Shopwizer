"""Build steps for the Growth Lab website. Standard library only.

  python3 scripts/build.py            sync tokens, render the draft legal pages and the contact phone line into site/
  python3 scripts/build.py preview    also write dist/preview/ (pages for the private Claude artifact)
                                      and dist/browser/ (the same pages to open straight from a folder)
  python3 scripts/build.py package    also write dist/growth-lab-site.zip (the Vercel ready folder, with api/)

site/ stays deployable as it is, with no build step on Vercel. Run this after editing
tokens/tokens.css, anything in legal/, or config/contact.json.
"""
import base64
import html
import json
import pathlib
import re
import shutil
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
DIST = ROOT / "dist"


def sync_tokens():
    """Copies tokens.css into the site and regenerates tokens.json from it."""
    src = ROOT / "tokens" / "tokens.css"
    shutil.copy(src, SITE / "assets" / "css" / "tokens.css")
    groups = {"colour": {}, "type": {}, "layout": {}, "motion": {}}
    for name, value in re.findall(r"--(gl-[\w-]+):\s*([^;]+);", src.read_text(encoding="utf8")):
        value = value.strip()
        if value.startswith("#"):
            groups["colour"][name] = value
        elif any(s in name for s in ("font", "weight", "text", "track")):
            groups["type"][name] = value
        elif any(s in name for s in ("ease", "cycle")):
            groups["motion"][name] = value
        else:
            groups["layout"][name] = value
    doc = {"$description": "Growth Lab website tokens. Generated from tokens/tokens.css. Rules: DESIGN_SYSTEM.md", **groups}
    (ROOT / "tokens" / "tokens.json").write_text(json.dumps(doc, indent=2) + "\n", encoding="utf8")


def inline_md(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"\*(.+?)\*", r"<em>\1</em>", text)
    text = re.sub(r"([\w.+-]+@[\w-]+(?:\.[\w-]+)+)", r'<a href="mailto:\1">\1</a>', text)
    return text


def md_to_html(md):
    """Enough Markdown for the legal drafts: headings (levels 1 to 3), paragraphs, bullet lists, bold, emphasis."""
    out, para, items = [], [], []

    def flush():
        if para:
            text = " ".join(para)
            cls = ' class="draft-banner"' if text.startswith("**Draft") else ""
            out.append(f"<p{cls}>{inline_md(text)}</p>")
            para.clear()
        if items:
            out.append("<ul>" + "".join(f"<li>{inline_md(i)}</li>" for i in items) + "</ul>")
            items.clear()

    for line in md.splitlines():
        s = line.strip()
        if not s:
            flush()
        elif s.startswith("### "):
            flush()
            out.append(f"<h3>{inline_md(s[4:])}</h3>")
        elif s.startswith("## "):
            flush()
            out.append(f"<h2>{inline_md(s[3:])}</h2>")
        elif s.startswith("# "):
            flush()
            out.append(f"<h1>{inline_md(s[2:])}</h1>")
        elif s.startswith("- "):
            if para:
                flush()
            items.append(s[2:])
        else:
            para.append(s)
    flush()
    return "\n".join(out)


def logo_markup():
    svg = (SITE / "assets" / "brand" / "growthlab-logo.svg").read_text(encoding="utf8").strip()
    return svg.replace("<svg ", '<svg class="logo" ', 1)


